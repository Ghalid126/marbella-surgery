<h3>How does it work?</h3>
<p>The treatment works by delivering radio frequency 
energy to heat the subsurface layers of skin in order 
to cause collagen contraction and remodelling, 
resulting in tighter, younger looking skin. The device 
uses sophisticated technology that controls the 
divergence of energy, directing the radio frequency 
waves through the epidermis and forcing them 
deeper, resulting in collagen remodelling and 
volumetric tightening. Basically, by delivering energy 
to the deepest layers of skin, the 3DEEP stimulates 
new collagen production and improves skin surface 
texture. As new healthier collagen is formed, 
tighter, more natural looking and firmer skin will be 
produced.<br>
The gradual improvement in your skin will 
continue even after completion of the treatment 
series.</p>
<p>&nbsp;</p>

<h3>What are the differences between the 
3DEEP and the other RF devices available on 
the market? </h3>
<p>Firstly, this is one of the few FDA approved devices 
which means that studies have been conducted to 
prove its efficiency and safety. <br>
Secondly, unlike unipolar energy which is very 
painful for the patient, and bipolar energy which 
is harder to control, this newest radio frequency 
uses an advanced, multi-source, phase-controlled 
technology treatment which delivers energy safely 
and precisely for maximum effectiveness with no 
patient discomfort.<br>
Thirdly, the unique benefit of this treatment is 
that it can be used on all skin types without the risk 
of hyperpigmentation. EndyMed™ is appropriate for 
both women and men and for all skin types from fair 
to dark, including tanned skins and can be used any 
time of the year.<br>
Because of its ability to target specific areas, 
you can choose a facial tightening procedure, body 
tightening treatment, or body contouring treatments. 
The 3DEEP treats the face, neck, décolletage (upper 
torso just above the breasts), upper arms, thigh, 
abdomen, hips and buttocks. EndyMed 3DEEP™ 
can also shape, smooth and tighten skin in smaller, 
harder-to-treat areas, such as the neck, upper arms, 
chest and knees.</p>
<p>&nbsp;</p>

<h3>The newest treatment 
that will lift and tighten 
skin without surgery, treat 
wrinkles and cellulite 
with no pain or downtime</h3>
<p>During the procedure, the device is placed on 
the skin’s surface and gently massaged over the 
treatment area in a circular motion. The area slowly 
warms as energy is delivered into the skin. Many 
