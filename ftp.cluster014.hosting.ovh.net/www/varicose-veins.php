								<h2>Varicose Veins</h2>
								<h3>What are they?</h3>
<p>Varicose veins are enlarged veins that can be flesh colored, dark purple or blue. They often look like cords and appear twisted and bulging. They are swollen and raised above the surface of the skin. Varicose veins are commonly found on the backs of the calves or on the inside of the leg, anywhere from groin to ankle.</p>
<p>&nbsp;</p>
<h3>How do they occur?</h3>
<p>Arteries carry blood from the heart out to every part of the body while veins return blood from the extremities to the heart (to be once again enriched with oxygen). As we are standing up or sitting down most of the time, leg veins must work against gravity to return the blood to the heart.</p>
<p>&nbsp;</p>
<p>To counteract the effect of gravity, there is a valve system inside vein’s lumen. The one way valves in the veins open to allow blood to flow upward, towards the heart, and then close to prevent it from flowing backwards. Varicose vein occur when the valves do not close properly. This is allowing blood to flow backward (venous reflux), increasing the venous pressure and inducing pooling of blood in the vein that causes it to enlarge.</p>
<p>&nbsp;</p>
<h3>What is the cause?</h3>
<p>Varicose veins are a very common problem. Women are more affected than men. More precisely, around 40% of women and 25% of men age 40-49 years and 70 % of women and 45% of men age 60-69 years suffer from some form of vein problem. This is almost always due to genetic predisposition. In other words, most people «inherit» their varicose veins. They appear first usually after puberty and worsen with time, particularly under the stresses imposed by pregnancy and hormonal changes. Other factors include age, prolonged standing, obesity, hormone therapy and leg trauma.</p>
<p>&nbsp;</p>
<h3>What are the symptoms?</h3>
<p>Apart from the unsightly aspect, most common symptoms are:</p>
<ul style="padding-top:0.75em;padding-left:0.5em;">
<li style="line-height:1.75em;">• Aching pain in the legs or feet, tired legs, leg heaviness</li>
<li style="line-height:1.75em;">• Burning, throbbing or itching with irritated rash in the legs</li>
<li style="line-height:1.75em;">• Swelling and numbness in the legs, restless leg syndrome</li>
<li style="line-height:1.75em;">• Pigmentation changes, inflammation, ulceration and bleeding in advanced cases Varicose veins and spider veins are always abnormal veins and will not disappear without treatment.</li>
</ul>
