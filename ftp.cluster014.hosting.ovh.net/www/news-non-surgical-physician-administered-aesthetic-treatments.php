                                <h3>Non Surgical Physician Administered Aesthetic Treatments</h3>
								<p>The renowned Marbella Vein Clinic is now offering non-surgical, 
physician-administered aesthetic treatments which can improve the 
appearance of frown lines, sunken cheeks, uneven lips, tired eyes 
and even acne scars.</p>
<p>&nbsp;</p>
<p>Having treated 
thousands of 
patients with vascular 
problems, improving their comfort as 
well as the aesthetic 
concern in their legs, hands and face, it 
became obvious that a more complete 
approach could increase the satisfaction 
of our patients. I opted to add non invasive 
cosmetic treatments to the list of services 
that our clinic offers, as it proceeds with the 
concept of global approach to well being 
and beauty enhancement. The tremendous development of non invasive methods for aesthetic improvement now allows 
us to obtain very good results in a very 
short time, think “lunch time procedures”.
I have extensive experience in injection 
treatment and being a board certified 
surgeon and former professor of anatomy, 
I have a very good knowledge of the 
anatomy, so I decided a few years ago, to 
learn, train and develop the field of fillers 
and neuromodulator injections in my practice and 
complete a Master in aesthetic medicine.</p>
<p>&nbsp;</p>

<h3>Provide Patients With The Best</h3>
<p>We can provide patients with the best 
methods of minimally invasive treatments 
that are used for beauty enhancement 
and skin improvement. First, Neuromodulator is used 
to treat “dynamic” wrinkles.</p>
<p>&nbsp;</p>
<p>When talking about filler products, there 
are numerous products available in Europe 
with different effects. In our clinic, safety 
is our first concern and, for this reason, we 
are using only pure hyaluronic acid which is 
a natural component of our body. We use 
mainly three brands : Restylane°, Teosyal°,a 
Swiss product, and Juvederm°. These so 
called ‘Neuromodulator Parties’ do worry me, as there 
are strict rules with aesthetic procedures 
and a knowledge of the anatomy is paramount. They may be cheaper but it comes 
at a high price.
</p>
<p>&nbsp;</p>

<h3>Unnatural “Plastic Look”</h3>
 

<p>We all have seen the results of those 
extreme aesthetic procedures giving the 
unnatural “plastic look” that was popular 
in the USA and this should certainly be 
avoided. I feel that this type of procedure 
should be soft and adapted to the patient 
morphology, enhancing it elegantly to 
obtain the most natural look. 
</p>
<p>&nbsp;</p>

<h3>Different Tools and Products</h3>
<p>We have different tools and products for 
beauty enhancement. We always start 
by a careful and complete analysis of 
the patient morphology and skin condition, assessing the needs, indication and 
limits of the procedure. We are convinced 
that when concerning neuromodulator and fillers 
injections, less is more and, ideally, the 
changes after treatment should bring 
an overall improvement and freshness, 
making the patient look younger without 
being obviously noticeable.</p>
<p>&nbsp;</p>

<h3>Youthful Hands</h3>
<p>My work really does complement each 
other. For example one of the first areas 
to show signs of ageing is the hands. 
You only have to look at the media 
uproar over Madonna when she was 
photographed with veiny, hollow hands. 
I wasn’t surprised to see a few months 
later when she appeared with smooth, 
youthful hands. It was the only thing that 
was giving away her age. Depending on 
what is needed we can treat the hand 
area in three stages. Firstly the removing 
of any venous concerns. Next we fill out 
any areas where there is a loss of tissue, 
to achieve a plumping effect. Finally any 
age spots can be treated with cryotherapy. The latter combination can also 
achieve great results on the décolleté 
area, where excessive sunbathing leads 
to a crepey effect.</p>
<p>&nbsp;</p>

<h3>Asymmetrical Lips</h3>
<p>One of my favourite cases so far has 
been a young lady, in her early 3O’s who 
came to me enquiring about treatment 
for asymmetrical lips. This problem was 
affecting her confidence. After an initial 
assessment, I opted for a small amount of 
filler to even out the lips. A week later she 
came back and said that she felt more 
positive about herself. That is the best 
result that you could ask for.</p>
