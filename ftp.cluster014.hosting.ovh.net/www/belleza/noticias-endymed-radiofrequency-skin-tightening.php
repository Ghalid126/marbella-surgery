<h3>WHAT MAKES 3DEEP 
STAND OUT?</h3>
<p>Ideal for skin that has lost its spring, it 
is a simple, quick and painless procedure, which provides excellent results 
for body contouring and facial skin 
tightening. All RF treatments work by 
delivering radio frequency energy to 
heat the sub-surface layers of the skin 
in order to cause collagen contraction 
and remodelling, resulting in tighter, 
younger looking skin. But, because 
EndyMed uses an advanced, multisource, phase-controlled technology, 
this newest radio frequency treatment 
can deliver energy more safely and 
precisely for maximum effectiveness 
with no patient discomfort.</p>
