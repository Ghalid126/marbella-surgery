								<h2>Sclerotherapy / Foam Treatment</h2>
<p>Microsclerotherapy involves injection of the diseased vein with a tiny needle. According to size and location, veins are injected with foam or liquid that irritates the vein wall.</p>
<p>&nbsp;</p>
<p>Microfoam injection induces a longer contact of the sclerosing agent with the vein wall, allowing the use of less concentrated solution.</p>
<p>&nbsp;</p>
<p>Sclerotherapy remains the «gold standard» in the treatment of telangiectasias or spider veins.</p>
<p>&nbsp;</p>
<p>In response, the veins collapse and are reabsorbed. The surface veins are no longer visible. Several sessions may be needed depending on the extent of the area to be treated. The vast majority of small, clearly visible veins can be successfully treated.</p>
<p>&nbsp;</p>
<p>Once the vein has been injected, it can take between two and six weeks for it to completely disappear. It is possible to resume a normal life immediately after a treatment. Normal exercise, including swimming, can be resumed after 24 hours. To improve the precision of injection sclerotherapy, we use a polarized light system specially manufactured ensuring a precise identification of the diseased vessel. As all procedures undertaken at The Marbella Vein & Beauty Clinic, sclerotherapy is administered by a vascular specialist ensuring the best possible results.</p>
