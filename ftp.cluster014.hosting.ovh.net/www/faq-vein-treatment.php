								<h2>FAQ Varicose Vein Treatment</h2>
                                <h3>How do I begin leg vein treatment?</h3>
<p>During the initial consultation, you will undergo a general examination, your legs will be screened and a Colour Doppler ultrasound evaluation will be performed. The treatment that will suit you best, depending upon the size and extent of your problem, will be detailed. Any questions you may have will be answered.</p>
<p>&nbsp;</p>
<h3>What are varicose veins?</h3>
<p>Varicose veins are abnormally swollen or enlarged blood vessels in the leg caused by the failure of the valves in the veins. Varicose veins and spider veins can be found in 35% of women and 20% of men above the age of 20. They appear as either bulging and rope-like, or small and thread-like. They can result in aching, tired and swollen legs, create a burning, throbbing, or itching sensation. When left untreated, they can generate complictions as thrombosis, hypodermatis or venous ulcer. Varicose veins are a vascular disorder requiring treatment for medical reasons.<p>
<p>&nbsp;</p>
<h3>What causes varicose veins?</h3>
<p>Heredity is a primary factor in over 85 % of the cases of varicose and spider veins. Women are more likely to suffer from abnormal leg veins. Up to 40% of women in Europe may be affected. Hormonal factors including puberty, pregnancy, menopause, the use of birth control pills, estrogen, and progesterone further increase your chances of developing vein disorders. Other contributing factors include prolonged standing, obesity and leg injury.<p>
<p>&nbsp;</p>
<h3>What are spider veins?</h3>
<p>Telangiectasias called “spider” veins appear to be hormonally induced and are associated with pregnancy and menstruation. Although spider veins are not usually symptomatic, the accompanying reticular veins, found deeper in the skin, often cause discomfort. Reticular veins are also referred to as “feeder” veins. Many women have a combination of both varicose and spider veins. While they may seek treatment for cosmetic improvement, many female patients are in fact looking for relief from pain.<p>
<p>&nbsp;</p>
<h3>What is sclerotherapy?</h3>
<p>Sclerotherapy involves the use of a very small needle to inject a solution into the diseased veins. The solutions work by causing the veins to shrink, close off and gradually disappear. The needles used are very small and feel like a mosquito bite. Most people find this relatively painless. The success of the sclerotherapy relies upon the experience and skill of the vein surgeon. Choosing the right injection site, volume, concentration and “exposure time” make the difference between success and failure.<p>
<p>&nbsp;</p>
<h3>How many sclerotherapy sessions will I need?</h3>
<p>Sclerotherapy treatment sessions usually last 20 to 25 minutes. Every patient is different, and the number of Sclerotherapy treatment sessions needed varies depending on the severity of your condition. Most cases require two to six treatments, however, this is only a guideline and your individual case may be different. Improvement may show in as little as one or two weeks, but the best results are usually seen after several sclerotherapy treatment sessions.<p>
<p>&nbsp;</p>
<h3>What is the Endovenous Laser Ablation (vein laser treatment)?</h3>
<p>It can be described as “No surgery, no scar, no hospitalisation, no anaesthesia” technique. Vein laser treatment, Endovenous Laser Treatment (EVLA) is a new minimally invasive method for treating large varicose veins that in most cases eliminates the need for open surgery. It requires only local anaesthesia and no hospitalisation. A thin laser fibre is inserted into the faulty vein through a small opening. The entire procedure takes about one hour and causes minimal to no pain. Performed under ultrasound guidance, EVLA uses laser energy to treat the underlying cause of varicose veins by closing off the insufficiency vein to any future blood flow. Your body then naturally uses other healthy veins to return blood from the heart.</p>
<p>&nbsp;</p>
<p>Marbella Vein Clinic in Spain has been using EVLA since 2002. The Advanced Marbella Vein Clinic has been successfully treating hundreds of patients with the 980 Nm diode laser.</p>
<p>&nbsp;</p>
