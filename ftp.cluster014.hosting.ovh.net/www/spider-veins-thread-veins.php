								<h2>Spider Veins / Thread Veins</h2>
<p>Thread veins are similar to varicose veins, but they are smaller. They have many names, including:</p>
<ul style="padding-top:0.75em;padding-left:0.5em;">
<li style="line-height:1.75em;">• Spider veins</li>
<li style="line-height:1.75em;">• Broken veins (not an accurate name, because they are not actually broken)</li>
<li style="line-height:1.75em;">• Capillary veins</li>
</ul>
<p>&nbsp;</p>
<p>Small thread veins are red, but larger ones look purplish. They are closer to the surface of the skin than varicose veins and tend to develop in clusters anywhere on the body.</p>
<p>&nbsp;</p>
<p>They commonly appear on the surface of the thighs, calves and ankles and can also develop on the face and chest. Women are more likely than men to get spider veins. Heredity plays a major role in their development although some other factors may contribute to it like pregnancy and hormonal variations. Spider veins may be isolated or associated with an insufficiency of a larger “feeder” veins or underlying varicose veins. Ultrasound evaluation has to be performed prior to treatment to detect any larger diseased veins and, if so, the large vein will need to be treated first and eliminated or the spider vein treatment will be ineffective.</p>
<p>&nbsp;</p>
<p>Thread veins are cosmetically noticeable and unsightly. Furthermore, even if they are not a health threat, they can cause itching, burning, heaviness, and fatigue in the legs.</p>
<p>&nbsp;</p>
<p>Treatment of leg thread vein is usually done by injection sclerotherapy. Depending on the size, colour and depth of the vessel, and to ensure the best cosmetic results we use a combination of Foam Sclerotherapy, liquid microsclero therapy and laser. For thread veins on the face, neck and chest, laser is the treatment of choice since, in that location, spider veins respond very well to this type of treatment.</p>
