								<h2>Endovenous Laser Ablation</h2>
								<p>Endovenous Laser Ablation (EVLA) is a new minimally invasive method for treating large varicose veins that in most cases eliminates the need for open varicose vein surgery. It is a walk-in walk-out procedure performed under LOCAL ANAESTHESIA. It uses laser energy applied inside the incompetent vein to seal it shut. Once a laser-targeted varicose vein is treated by endovenous laser technique, the venous blood flow is re-routed from it to normal veins within the leg where it can effectively flow back to the heart and lungs.</p>
<p>&nbsp;</p>
<p>With EVLA, a small puncture is made in the leg and a laser fibre is inserted into the diseased vein allowing its treatment from inside the lumen. All large varicose veins are treated in one session in the same leg. This requires only micro-incisions and no skin sutures. The aesthetic results are excellent and only one hour after vein treatment, the patient walks out of the vein clinic and returns to normal activity the following day.</p>
<p>&nbsp;</p>
<p>A variety of laser wave lengths are in use for this procedure, including 810, 940, 980, 1064 and 1320 nm.</p>
