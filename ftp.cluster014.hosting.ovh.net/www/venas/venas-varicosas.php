								<h2>VARICES (Venas varicosas)</h2>
								<h3>¿ Que son las varices ?</h3>
<p>Las varices son venas dilatadas que se pueden tornar en distintos color  como azul o purpura, dando casi siempre un aspecto de cordon venoso, abultado o girado , que generalmente se hinchan y  aparecen en la superficie de la piel. Las varices, comunmente se encuentran en la parte inferios de la pierna en la zona posterior, aunque tambien se dan los casos desde la ingle hasta el tobillo.</p>
<p>&nbsp;</p>
<h3>¿ Por qué ocurre esto ?</h3>
<p>Las arterias mandan sangre desde el corazon a todo el cuerpo y las venas se encargan de devolver esa sangre al corazon ( Para volver a ser enriquecidas con oxigeno )
Cuando estamos de pie o sentados durante mucho tiempo, las venas de las piernas deben trabajar con mayor esfuerzo para devolver la sangre, contra gravedad, al corazon.
Dentro de las venas existe un sistema de valvulas, de manera, que las valvulas se abren para permitir el pasar el flujo sanguineo, y del mismo modo, se cierran para que no hay un reflujo de la sangre.<br /><br />
Cuando estas valvulas no funcionan correctamente, no permiten a la sangre volver al corazon y se produce lo que se conoce como reflujo venoso, aumentando de ese modo la presion venosa y el riesgo de estancamiento de la sangre, por lo que da lugar a esa dilatacion venosa.</p>
<p>&nbsp;</p>
<h3>¿ Que las causa ?</h3>
<p>Las varices son un problema muy comun. Y se dan mayor numero de casos de mujeres que en hombres, para ser mas precisos, sobre un 40% son mujeres y un 25% son hombres entre edades comprendidas entre los 40-49 años y el 70% de mujeres y el 45% de hombres en edades comprendidas entre los 60 -69 años, que de algun modo sufre cualquier alteracion venosa.
Normalmente, la causa principal es la herencia genetica, y la predisposicion a padecerlas. Las primeras suelen aparecer ya en la pubertad, y van empeorando con los años. En casos particulares, puede influenciar los embarazos, cambios hormonales y otros factores como la edad, la obesidad, terapias con hormonas o algunas lesiones traumaticas en las piernas.</p>
<p>&nbsp;</p>
<h3>¿ Cuales son los Sintomas ?</h3>
<p>Aparte del aspecto poco saluble que presentan, suelen estar acompañadas de una sintomatologia, lo mas comun es :<br /><br />
Sensacion de dolor en las piernas o en los pies, acompañado de pesadez en las piernas, piernas cansadas.<br />
Sensacion de quemazon, picor, escozor con irritacion en la pierna.<br />
Hinchazon y entumecimiento de las piernas, sindrome de no descansar las piernas.<br />
Cambios de pigmentacion, inflamacion, ulceracion y sangrado en casos avanzados.<br />
