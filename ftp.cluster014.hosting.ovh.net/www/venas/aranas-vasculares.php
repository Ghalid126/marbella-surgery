								<h2>ARAÑAS VASCULARES</h2>
								<p>Las arañas vasculares son parecidas a las varices</span>, pero mucho más pequeñas, y son conocidas por muchos nombres:</p>
<ul style="padding-top:0.75em;padding-left:0.5em;">
<li style="line-height:1.75em;">• Arañas vasculares</li>
<li style="line-height:1.75em;">• Venas rotas (no sería un nombre correcto, ya que realmente no están rotas)</li>
<li style="line-height:1.75em;">• Capilares</li>
</ul>
<br /><br />
<p>Estas pequeñas venas rojizas, aunque también se dan casos de ser mas largas y moradas, están muy cerca de la superficie de la piel como las varices y tienden a desarrolarse en cualquier parte del cuerpo. 
<br /><br />
Normalmente suelen aparecer en las piernas, muslos, tobillos…pero también se dan casos como en la cara o el pecho. Las mujeres son mas propensas a este tipo de problemas que los hombres. El factor hereditario juega un papel muy importante a la hora de aparecer, pero no es el único, también contribuyen factores como el embarazo o variaciones hormonales.
Las arañas vasculares pueden aparecer aisladas o asociadas a un problema de insuficiencia venosa mas importante o varices. El examen bajo ultrasonidos juega un papel muy importante a la hora de detectar su causa, y el tipo de tratamiento mas indicado para eliminarlas completamente y de manera efectiva.
<br /><br />
Las arañas vasculares son también un problemas estético, pero aparte de esto, pueden provocar picores, sensación de quemazón, pesadez o fatiga en las piernas.
Los tratamientos de arañas vasculares, se suelen realizar con escleroterapia, dependiendo del color, tamaño y profundidad del vaso, y para asegurar los mejores resultados estéticos, usaremos una combinación de escleroterapia en espuma, microescleroterapia liquida y láser.
<br /><br />
Para el tratamiento de arañas vasculares en la cara, nariz y el pecho, el láser es la mejor opción por su localización y por como responden las arañas vasculares al tratamiento.</p>
