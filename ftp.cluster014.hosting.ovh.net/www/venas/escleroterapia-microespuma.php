								<h2>ESCLEROTERAPIA con ESPUMA</h2>
<h2>MICROESCLEROTERAPIA</h2>
								
                                <p>La escleroterapia / microescleroterpia  son inyecciones para venas enfermas con una aguja  muy fina, de acuerdo con su tamaño y localización. La reacción que se produce dentro de la vena inyectada hace que ésta se cierre.
 <br /><br />
Las inyecciones de microespuma alcanzan con largo contacto del agente esclerosante con la paredse de la vena, permitiendo usar menos concentración de la medicación.
Es el procedimiento de elección para el tratamiento de las Telangiectasias.
 <br /><br />
En respuesta a la medicación, las venas colapsadas son reabsorvidas y desapararecen de la piel. El número de sesiones necesarias depende de la necesidad de cada paciente y la extensión del área a tratar. La gran mayoria de las venas pequeñas van desapareciendo sucesivamente tras ser tratadas. Una vez, que han sido tratadas, tardan en desaparecer completamente entre dos y seis semanas.
<br /><br />
Después del tratamiento se puede reanudar la vida cotidiana sin ningún inconveniente. Puede hacer ejercicio, incluso nadar 24 horas después.
<br /><br />
Para mejorar la precisión de las inyecciones de escleroterapia, usamos un sistema de  luz polarizada diseñada especialemente para la identificación de trastornos venosos.
<br /><br />
Todos los procedimientos se realizan en la clínica y la escleroterapia es administrada por un especialista vascular asegurando los mejores resultados posibles.</p>
<p>&nbsp;</p>
