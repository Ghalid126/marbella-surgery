								<h2>PREGUNTAS FRECUENTES SOBRE LAS VARICES</h2>
								<h3>COMO COMENZAR UN TRATAMIENTO VENOSO EN LAS PIERNAS ?</h3>
<p>Durante la primera consulta, después de un examen médico general, sus piernas serán examinadas con una ecografia doppler color. El tratamiento será personalizado, y en función de sus necesidades, del tamaño y extensión de su caso particular.
Y si tiene alguna duda, sólo tiene que preguntar, ya que responderemos a cualquiera de sus preguntas.</p>
<p>&nbsp;</p>

<h3>QUE SON LAS VARICES ?</h3>
<p>Las varices son vasos que no están en su estado normal, aparecen anormalmente abultadas, o con problemas dentro de los vasos venosos en las piernas, causados por el fallo de las válvulas de las venas. Las varices aparecen en un 55% de la población, siendo 35% de los casos mujeres y el 20% hombres, a partir de 20 años.
Suelen aparecer arañas vasculares o abultamientos de las venas, causando picores, tirantez, sensación de quemazón, piernas hinchadas y fatigadas,…pero si las dejamos sin tratar, pueden generar complicaciones como trombosis, hipodermitis o ulceras venosas. Las varices son un trastorno venoso que requiere de un tratamiento médico.</p>
<p>&nbsp;</p>

<h3>QUE CAUSA LAS VARICES ?</h3>
<p>El principal causante de las varices es el factor hereditario, en un 85% de los casos de varices y arañas vasculares. Siendo las mujeres el grupo que mas lo sufren. El 40% de las mujeres europeas sufren de insuficiencias venosas.
Factores hormonales en la pubertad, embarazo, menopausia, el uso de la píldora anticonceptiva, estrógenos y progesterona hacen que se desarrollen estos trastornos venosos, pero no son los únicos también contribuyen los estados prolongados estando de pie o sentados, la obesidad, heridas en las pierna.</p>
<p>&nbsp;</p>

<h3>QUE SON LAS ARAÑAS VASCULARES ?</h3>
<p>Las telangiectasias también llamadas arañas vasculares aparecen normalmente asociadas a factores hormonales, que se dan durante el embarazo y la menstruación. Aunque las arañas vasculares no suelen ser sintomáticas, viene acompañadas por venas reticulares, que se encuentran a mayor profundidad en la piel, y que causan bastantes incomodidades.
Las venas reticulares también son conocidas como “feeder”. Y en el caso de muchas mujeres, se dan la combinación de ambas junto a las varices.Y mientras que muchas personas lo ven como un tratamiento estético, muchas de las pacientes femeninas sufren los dolores y las molestias que éstas ocasionan.</p>
<p>&nbsp;</p>

<h3>QUE ES LA ESCLEROTERAPIA ?</h3>
<p>La escleroterapia es un tratamiento donde se usan unas pequeñas agujas para inyectar una solución dentro de las venas enfermas.
La solución funciona de manera que cierra, elimina y finalmente desaparecen esas venas.
Las agujas que se requieren para este tratamiento son de un pequeño calibre y la sensación es como una picadura de mosquito. Muchos pacientes coinciden en que no es un tratamiento doloroso.
Para conseguir unos resultados óptimos, el procedimiento lo debe hacer un médico experimentado, sabiendo elegir la inyección correcta, cantidad, tamaño de la vena, concentración, tiempos de exposición, que será lo que marque la diferencia entre un tratamiento correcto y el que no lo es.</p>
<p>&nbsp;</p>

<h3>CUANTAS SESIONES NECESITARE ?</h3>
<p>Las sesiones de escleroterapia, suelen durar unos 20-25 minutos normalmente. Cada paciente es diferente, y el número de sesiones varia en función de la severidad del caso.
Muchos de los casos suelen requerir entre dos y seis sesiones, sin embargo, esto es sólo una aproximación porque como ya dijimos antes depende de cada persona.
La mejora se aprecia a partir de una o dos semanas, pero los mejores resultados suelen verse después de varias sesiones.</p>
<p>&nbsp;</p>

<h3>QUE ES EL TRATAMIENTO LASER ?</h3>
<p>Puede ser descrito como aquel tratamiento, sin cirugía, sin cicatrices, sin hospitalización y sin anestesia.
<br><br>
El tratamiento de láser Endovenoso ( EVLA ) , es un método minimamente inmvasivo que trata venas de largo recorrido o profundidad, y que en la mayoria de los casos son eliminados con cirugía tradicional. Solo requiere anestesia local. La técnica consistre en introducir una fibra de láser dentro de la vena a través de una pequeña incisión.
Requiere un tiempo total de una hora y no es doloroso. Se realiza con ayuda de una guia de ultrasonidos , y EVLA precisa de una energía del láser que consigue cerrar la vena y evitar problemas posteriores. El cuerpo, de manera natural busca otras venas sanas por donde fluir la sangre y retornarla al corazón.
Nosotros llevamos utilizando esta técnica desde 2002, siendo efectiva con cientos de pacientes con el diodo de 980 Nm.
<br><br>
Recientemente, las nuevas tecnologías han avanzado y desarrollado nuevos sitemas de laser : El ELVeS* Painless 1470 Nm con una fibra Radial* Painless, siendo nuestra clínica de las primeras en España de tener esta nueva tecnología para ofrecersela a nuestros pacientes.
Este sistema nos permite realizar tratamientos muy eficientes con láser de baja potencia, son efectos secundarios, sin hematomas ni dolor post operatorio.</p>

<p>&nbsp;</p>
<h3>ES DOLOROSO EL PROCEDIMIENTO Y CUANTO DURA ?</h3>
<p>El tratamiento se realiza bajo anestesia local. Algunos pacientes han experimentado alguna pequeña molestia. La duración del tratamiento depende de lo extensa que sea la microflebectomia que se asocia cuando un paciente requiere un tratamiento de láser Endovenoso, pero todo queda tratado en una sesión.</p>
<p>&nbsp;</p>

<h3>TENDRE DOLORES DESPUES DEL TRATAMIENTO CON LASER ENDOVENOSO ?</h3>
<p>La introducción del nuevo láser ELVeS * Painless se usa en conjunto con una fibra radial, y esto abre una nueva era en el tratamiento de láser Endovenoso. La mayoria de los pacientes no han presentado ni dolor ni molestias ni durante ni después del tratamiento. Después de haber finalizado el tratamiento, el paciente puede andar y al dia siguiente volver a su vida cotidiana.</p>
<p>&nbsp;</p>

<h3>QUE COMPLICACIONES SE ASOCIAN A ESTE TRATAMIENTO ?</h3>
<p>Las complicaciones potenciales con las mismas que en cualquier tratamiento médico. La única mínima complicación que se puede experimentar después del láser Endovenoso, es en un reducido numero de paciente parestesia temporal ( hormigueos ), en algunas de las zonas tratadas.</p>
<p>&nbsp;</p>

<h3>COMO CIRCULARA MI SANGRE SI ELIMINO LAS VARICES ?</h3>
<p>Las varices son un problema para la circulación, ya que sangre que refluye por ellas provocan reflujos ( la sangre sube y baja dentro del vaso pero no sale del mismo ), impidiendo un correcto flujo sanguíneo. Al cerrar o eliminar las venas que no son funcionales, la sangre busca entre las otras venas que si funcionan para realizar el retorno venoso.</p>
<p>&nbsp;</p>
<h3>SI LAS VENAS QUE NO FUNCIONAN SE CIERRAN, Y LA SANGRE REFLUYE POR OTRAS, NO PROVOCARAN QUE LAS VENAS BUENAS SE VUELVAN VARICOSAS ?</h3>
<p>Si hace mucho tiempo que sufre de varices, su cuerpo seguramente, ya habrá buscado un flujo alternativo por donde retornar la sangre por venas adyacentes para hacer una compensación sanguínea. Por ello, es necesario eliminar las que no funcionan, para que no sigan recargando a las demás venas y mejorar el retorno venoso .Al eliminarlas, se mejora la circulación venosa, porque ya no existen varices que las entorpezcan, y los síntomas mejoran de manera efectiva tras el tratamiento, y esto ocurre porque el cuerpo redirige el flujo sanguíneo a otros vasos mas fuertes, sanos y profundo dentro de la pierna.</p>
<p>&nbsp;</p>
<h3>QUE PASARIA SI NECESITO UN BYPASS EN EL FUTURO, Y LA VENA SAFENA HA SIDO ELIMINADA ?</h3>
<p>Por lógica, si esa vena estaba enferma y no funcionaba bien ni hacía su función correctamente, no sería ni mucho menos una vena apta para un bypass.</p>
<p>&nbsp;</p>
<h3>CUBRIRA MI SEGURO ESTE TRATAMIENTO ?</h3>
<p>Casi todas las compañias aseguradoras cubren estos tratamientos, ya que son medicamente necesarios. En estos casos, en nuestra clínica le ayudaremos en todo lo que podamos, le daremos todas la información médica y los informes que necesite para su seguro médico, ayudarle a buscar formas de reembolso o garantías en su seguro.</p>
<p>&nbsp;</p>
<h3>QUE PASARIA SI NO ME TRATARA LAS VARICES ?</h3>
<p>La insuficiencia venosa es una enfermedad progresiva, que si no se trata, lógicamente puede empeorar. En la mayoría de los casos, en casos severos, las varices provocan daños en la piel, ulceraciones, coágulos en la sangre. Tomar  una decisión sobre las varices y su tratamiento, debe ser algo que debe hacerse lo antes posible, para evitar daños colaterales, para hacerlo de manera fácil y controlada.</p>
<p>&nbsp;</p>
<h3>QUE DEBERIA BUSCAR EN UN DOCTOR ?</h3>
<p>La experiencia es importante. La insuficiencia venosa es algo complejo y único en cada paciente. A pesar de eso, es importante buscar a un especialista con una experiencia adquirida acerca de estos tratamientos y que conozca el espectro completo de las enfermedades venosas.</p>
